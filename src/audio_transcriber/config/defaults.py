"""Значения по умолчанию, не зависящие от подсистем.

Вынесены в отдельный модуль, чтобы :mod:`audio_transcriber.config` не
импортировал из :mod:`audio_transcriber.llm` (инверсия зависимостей): и
конфигурация, и клиент LLM берут значение отсюда.
"""

from __future__ import annotations

# 4096 токенов: 7B Q4_K_M влезает в 8 ГБ VRAM вместе с рабочим столом.
DEFAULT_CONTEXT_SIZE = 4096

#: Таймаут одного HTTP-запроса к ``llama-server`` (секунды). 600 с — с запасом
#: покрывает длительную генерацию резюме/правок на CPU-деградации, но не даёт
#: клиенту висеть вечно. Настраивается через ``LLM_REQUEST_TIMEOUT``.
DEFAULT_LLM_REQUEST_TIMEOUT = 600.0

#: Провайдер LLM-постобработки по умолчанию — локальный ``llama-server``.
#: Значение ``openai`` включает внешний OpenAI-совместимый API (текст уходит
#: за пределы машины).
DEFAULT_LLM_PROVIDER = "llama"

#: Допустимые провайдеры LLM-постобработки.
VALID_LLM_PROVIDERS = ("llama", "openai")

#: Имя/путь внешнего Rust-CLI ``deep-filter`` (DeepFilterNet), которым
#: выполняется шумоподавление. Ищется в ``PATH``, если не задан явный путь.
#: Заменяет Python-пакет ``deepfilternet`` (нет колёс >cp311, тянет numpy<2).
DEFAULT_DEEP_FILTER_BINARY = "deep-filter"

# Порог «низкой уверенности» ASR: реплики со средним ``avg_logprob`` ниже
# этого значения помечаются в экспорте. Логвероятности <= 0, поэтому -1.0
# отмечает лишь заметно неуверенные сегменты; более отрицательное значение
# (например, -10) фактически отключает пометку.
DEFAULT_LOW_CONFIDENCE_THRESHOLD = -1.0

# Порог косинусного сходства для сопоставления диаризованного говорящего с
# образцом голоса (enrollment). Ниже порога имя не присваивается — говорящий
# остаётся «Спикер N», чтобы не подписать реплики чужим голосом.
DEFAULT_ENROLLMENT_MIN_SIMILARITY = 0.6

#: Папка-библиотека образцов голоса по умолчанию (относительно каталога запуска).
#: Файлы ``<Имя>.wav`` трактуются как образцы и участвуют в enrollment.
DEFAULT_VOICES_DIR = "voices"

#: Подготавливать образцы голоса перед сохранением в библиотеку и при
#: enrollment: VAD-обрезка тишины (речь + небольшой запас), ограничение
#: длительности 3–10 с и лёгкая RMS-нормализация. Одна и та же обработка
#: применяется и к эталону, и к окнам говорящего — иначе домены «эталон» и
#: «тест» расходятся и косинусные сходства падают (см. #29).
DEFAULT_REFERENCE_PREPARE = True

#: Минимальная длительность чистой речи образца (секунды). Короче — нестабильный
#: эмбеддинг говорящего: образец принимается, но помечается предупреждением.
DEFAULT_ENROLLMENT_MIN_SAMPLE_SECONDS = 3.0

#: Максимальная длительность образца (секунды). Окно эмбеддера WeSpeaker ~5 с,
#: поэтому более длинные эталоны обрезаются до этого предела (10 с — с запасом).
DEFAULT_ENROLLMENT_MAX_SAMPLE_SECONDS = 10.0

#: Целевой уровень RMS образца в dBFS для лёгкой нормализации (increase_only):
#: тихие клипы усиливаются до этого уровня, громкие не ослабляются. −30 dBFS —
#: умеренный уровень, не усиливающий шум (peak-нормализация рискованнее).
DEFAULT_REFERENCE_TARGET_DBFS = -30.0

#: Значение по умолчанию для гиперпараметра диаризации
#: ``segmentation.min_duration_off`` (секунды). Это главный рычаг против
#: дробления реплик: короткие паузы внутри одной реплики склеиваются. У
#: pyannote по умолчанию 0.0, но замеры на реальном материале показали, что
#: 0.5 заметно уменьшает число сегментов (30 -> 20 -> 15 при 0 -> 0.5 -> 1.0)
#: при том же числе говорящих. Поэтому наш дефолт — 0.5.
DEFAULT_DIARIZATION_MIN_DURATION_OFF = 0.5

# --- Диаризация: выбор движка и параметры NeMo-Speech.cpp (#62) --------------
#: Движок диаризации по умолчанию: ``auto`` — pyannote, если NeMo-Speech.cpp
#: не сконфигурирован (бинарник недоступен), иначе nemo-speech.
DEFAULT_DIARIZATION_ENGINE = "auto"

#: Допустимые движки диаризации.
VALID_DIARIZATION_ENGINES = ("auto", "pyannote", "nemo-speech", "hybrid")

#: Допустимые linkage глобальной кластеризации гибрида. ``ward`` требует
#: евклидовой метрики, ``complete``/``average``/``single`` — косинусной.
VALID_DIARIZATION_LINKAGES = ("ward", "complete", "average")

#: Имя/путь бинарника NeMo-Speech.cpp по умолчанию (ищется в ``PATH``).
DEFAULT_NEMO_SPEECH_BINARY = "nemo-speech"

#: Модель диаризации NeMo-Speech.cpp по умолчанию — Sortformer streaming,
#: 4 спикера (CC-BY-4.0, q8_0 ~140 МиБ). Может быть именем из каталога,
#: HF-репозиторием или путём к ``.gguf``.
DEFAULT_NEMO_SPEECH_MODEL = "nvidia/diar_streaming_sortformer_4spk-v2"

#: Устройство для ``nemo-speech diarize --device`` по умолчанию.
DEFAULT_NEMO_SPEECH_DEVICE = "auto"

#: Допустимые устройства NeMo-Speech.cpp (Vulkan-сборка использует GPU).
VALID_NEMO_SPEECH_DEVICES = ("auto", "vulkan", "cpu")

#: Максимум спикеров у модели Sortformer (EEND, фиксированная голова на 4).
#: ``num_speakers``/``max_speakers`` выше лимита не поддерживаются — движок
#: предупреждает и продолжается с этим потолком.
NEMO_SPEECH_MAX_SPEAKERS = 4

# --- Оценщик числа говорящих (#64) ------------------------------------------
#: Включён ли дешёвый оценщик числа говорящих (sherpa-onnx). Он нужен режиму
#: ``auto``, чтобы выбрать движок: <= лимита — nemo-speech (быстро), больше —
#: pyannote (точно). При недоступности sherpa-onnx/моделей оценка мягко
#: деградирует в ``None``, и ``auto`` безопасно выбирает pyannote.
DEFAULT_DIARIZATION_ESTIMATE_ENABLED = True

#: Сколько секунд речи анализировать оценщику (а не только начало записи).
#: Фрагменты равномерно распределяются по всей записи. Мало — быстрее, но
#: грубее; много — точнее. Дефолт выверен на реальной записи (15 мин → ~6 с).
DEFAULT_DIARIZATION_ESTIMATE_SECONDS = 30.0

#: Порог косинусного расстояния агломеративной кластеризации эмбеддингов
#: оценщика (диапазон (0; 2)). Ниже — больше «говорящих», выше — меньше.
#: Кластеризация идёт с ``complete``-linkage (не ``average``): ``average``
#: строит «цепочки» и склеивает говорящих. 0.50 настроен под complete+cosine
#: на реальной записи (Отказоустойчивость_28_09.mp4, ~12 участников):
#: 0.50 даёт k≈14 / доля топ-кластера ≈31% против 68–78% у average.
DEFAULT_DIARIZATION_ESTIMATE_THRESHOLD = 0.50

#: Модель эмбеддингов говорящего для оценщика: имя файла в каталоге моделей
#: оценщика (по умолчанию скачивается с релизов k2-fsa/sherpa-onnx) либо путь
#: к локальному ``.onnx``. CAM++ zh/en (16 кГц) — компактная (≈28 МиБ) и
#: быстрая; архитектура не требует PyTorch.
DEFAULT_DIARIZATION_ESTIMATE_MODEL = (
    "3dspeaker_speech_campplus_sv_zh_en_16k-common_advanced.onnx"
)

#: Верхняя граница числа говорящих, до которой ``auto`` выбирает быстрый
#: nemo-speech. Совпадает с лимитом модели Sortformer (4 спикера). Выше —
#: ``auto`` уходит на pyannote, чтобы не потерять говорящих.
DEFAULT_DIARIZATION_ROUTE_MAX_SPEAKERS = NEMO_SPEECH_MAX_SPEAKERS

# --- Гибридная диаризация (#64, часть 2) ------------------------------------
#: Включена ли гибридная диаризация (оконный EEND nemo-speech + глобальная
#: склейка локальных говорящих по эмбеддингам). Она обходит лимит Sortformer в
#: 4 спикера и даёт быстрый движок для записей с >4 говорящими. При ``auto`` и
#: N выше ``DIARIZATION_ROUTE_MAX_SPEAKERS`` выбирается гибрид, если доступны
#: бинарник nemo-speech и sherpa-onnx с моделью эмбеддингов; иначе — pyannote.
DEFAULT_DIARIZATION_HYBRID_ENABLED = True

#: Длительность окна гибридной диаризации (секунды). Короче окно — выше шанс,
#: что в него попадут <=4 говорящих (лимит Sortformer), но больше запусков.
DEFAULT_DIARIZATION_HYBRID_WINDOW_SECONDS = 90.0

#: Перекрытие соседних окон (секунды). Нужно, чтобы речь на границе не терялась:
#: эмбеддинги локальных говорящих берутся из полного окна, а сегменты на
#: выходе распределяются по непересекающимся «зонам владения» (дублей нет).
DEFAULT_DIARIZATION_HYBRID_OVERLAP_SECONDS = 2.0

#: Минимальная суммарная длительность речи локального говорящего в окне
#: (секунды), при которой считается его эмбеддинг. Короче — вектор ненадёжен.
#: 3.0 с согласовано с минимальной длительностью образца enrollment и отсекает
#: «микро-кластеры» из односложных реплик (на реальной записи повышение 1.5→3.0
#: убирает мусорные кластеры «Спикер N» на доли процента времени).
DEFAULT_DIARIZATION_HYBRID_MIN_SPEAKER_SECONDS = 3.0

#: Минимальная суммарная длительность речи локального говорящего (секунды), при
#: которой он **не** выбрасывается, даже если не дотягивает до
#: :data:`DEFAULT_DIARIZATION_HYBRID_MIN_SPEAKER_SECONDS`. Ниже этого порога
#: эмбеддинг заведомо неинформативен; на нём и выше — короткая вставка другого
#: участника (1–1.5 с) сохраняется отдельным кластером, а не приписывается
#: соседу или не теряется (#93). 0.5 с согласовано с ``MIN_SEGMENT_SECONDS``
#: enrollment. Порог намеренно не конфигурируем: он защищает от потери короткой
#: речи, а не задаёт качество длинных кластеров.
DEFAULT_DIARIZATION_HYBRID_MIN_SHORT_SPEAKER_SECONDS = 0.5

#: Максимум аудио одного локального говорящего в окне, склеиваемого для одного
#: эмбеддинга (секунды). Ограничивает стоимость инференса CAM++.
DEFAULT_DIARIZATION_HYBRID_MAX_EMBEDDING_SECONDS = 15.0

#: Linkage глобальной кластеризации эмбеддингов гибрида по порогу.
#: ``ward`` (евклидова метрика на L2-нормированных векторах) даёт на реальных
#: данных заметно лучшее распределение, чем ``complete``/cosine: меньше
#: «хвостовых» кластеров и ниже TV к долям реплик протокола. ``complete`` рушится
#: при 0.55 (топ-кластер 60% сегментов), а ``ward`` при пороге 1.30 — k≈10-11,
#: топ ~36% и TV≈0.12. Смена linkage меняет смысл порога: см.
#: :data:`DEFAULT_DIARIZATION_HYBRID_THRESHOLD`.
DEFAULT_DIARIZATION_HYBRID_LINKAGE = "ward"

#: Порог глобальной кластеризации эмбеддингов гибрида. Для ``ward`` порог
#: задаётся в единицах **евклидова** расстояния на L2-нормированных векторах
#: (диапазон ``0..2``), поэтому НЕ совпадает с косинусным порогом оценщика
#: :data:`DEFAULT_DIARIZATION_ESTIMATE_THRESHOLD` (0.50). Значение 1.30 подобрано
#: на реальной записи (Отказоустойчивость_28_09.mp4, denoised-эмбеддинги):
#: k≈10-11, крупнейший кластер ~36% времени, TV к долям реплик протокола
#: ≈0.12 (против complete/0.50 → k≈16, топ ~48%, TV ≈0.19). Оценка числа
#: говорящих (переданная гибриду как мягкий ориентир) здесь НЕ форсирует точное
#: число кластеров.
DEFAULT_DIARIZATION_HYBRID_THRESHOLD = 1.30

#: Переобрабатывать ли «перегруженные» окна гибрида мелкими окнами (#68).
#: Если в окне задействованы все 4 головы Sortformer и сегменты сильно
#: «путаются» (частая смена говорящего), не исключено, что реальных говорящих
#: больше 4 и модель их слила. Такое окно режется на более мелкие окна, а
#: локальные говорящие затем склеиваются глобально по эмбеддингам.
DEFAULT_DIARIZATION_HYBRID_OVERLOAD_SPLIT = True

#: Длительность мелкого окна при переобработке «перегруженного» окна (секунды).
DEFAULT_DIARIZATION_HYBRID_SUBWINDOW_SECONDS = 30.0

#: Максимальная глубина рекурсивной нарезки «перегруженного» окна. 0 — не
#: дробить; 1 — один уровень (по умолчанию, достаточно и дёшево).
DEFAULT_DIARIZATION_HYBRID_MAX_SPLIT_DEPTH = 1

#: Порог «перегруженности»: доля смен говорящего между соседними сегментами
#: окна. Выше порога при занятых всех головах окно считается «путаным».
DEFAULT_DIARIZATION_HYBRID_OVERLOAD_CHANGE_RATE = 0.7

#: Минимум сегментов в окне, чтобы судить о его «перегруженности» (мало
#: сегментов — статистика шумная, дробление не оправдано).
DEFAULT_DIARIZATION_HYBRID_OVERLOAD_MIN_SEGMENTS = 10

#: Разделяемые библиотеки, которые нельзя добавлять в ``LD_LIBRARY_PATH`` из
#: каталога библиотек движка: бандл-libstdc++/libgcc_s затеняют системные и
#: ломают загрузку Vulkan-ICD (Radeon). При их наличии каталог не подмешивается.
NEMO_SPEECH_FORBIDDEN_LIBS = ("libstdc++.so.6", "libgcc_s.so.1")

#: Путь к SQLite-базе глоссария по умолчанию (относительно каталога запуска).
#: Файл создаётся при первом импорте или запуске (``glossary import``).
DEFAULT_GLOSSARY_DB = "glossary.db"

#: Модель GigaAM v3 (RU) для бэкенда ``gigaam`` (через onnx-asr). E2E RNN-T
