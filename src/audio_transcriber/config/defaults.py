DEFAULT_HYBRID_LOW_LOGPROB_THRESHOLD = -1.0
# Вероятность отсутствия речи (Whisper) выше порога — сегмент «плохой».
DEFAULT_HYBRID_NO_SPEECH_THRESHOLD = 0.6
