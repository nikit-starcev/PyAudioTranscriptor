DEFAULT_GIGAAM_MODEL = "gigaam-v3-e2e-rnnt"

#: Модель VAD ``onnx-asr``, которой GigaAM режет длинное аудио на сегменты.
DEFAULT_GIGAAM_VAD_MODEL = "silero"

# --- Гибридный ASR (#57): доработка «плохих» сегментов Whisper ---
